static int failures = 0;

static void check(bool cond, const char* what) {
    if (!cond) {
        std::fprintf(stderr, "FAIL: %s\n", what);
        ++failures;
    }
}

static void testScript() {
    const std::string text =
        "# Generated by UI editor\r\n"
        "<LEGACY clsid=GZWinGen iid=IGZWinGen id=0xcda360ce area=(137,85,839,647) fillcolor=(0,0,0) "
        "caption=\"Main menu\" winflag_visible=yes >\r\n"
        "<CHILDREN>\r\n"
        "   <LEGACY clsid=GZWinBMP id=0x0da36c7d area=(0,-30,1044,788) image={499db772,ccc9af70} winflag_visible=no >\r\n"
        "   <LEGACY clsid=GZWinText caption=\"two\r\nlines > here\" captionres={7f3a262a,00870001} transparent "
        "outlinecolor=(127,136,255)(255,242,255) >\r\n"
        "   <CHILDREN>\r\n"
        "      <LEGACY clsid=GZWinScrollbar2 id=0x1008 thumbimage={856ddbac,499db772,ccc30005} >\r\n"
        "   </CHILDREN>\r\n"
        "</CHILDREN>\r\n"
        "<LEGACY clsid=0x4d9ccdb1 id=0x00000abc >\r\n";
    const UiScript s = UiScript::parse(text);
    check(s.warnings.empty(), "script parses without warnings");
    check(s.roots.size() == 2, "two roots");
    check(s.elementCount() == 5, "five windows");
    const UiElement& root = s.roots[0];
    check(root.clsid() == "GZWinGen" && root.id() == 0xCDA360CE, "root class and id");
    check(root.area() == std::array<int, 4>{137, 85, 839, 647}, "root area");
    check(root.visible() && root.get("caption") == "Main menu", "root caption and flag");
    check(root.children.size() == 2, "root children");
    const UiElement& bmp = root.children[0];
    check(bmp.area()[1] == -30 && !bmp.visible(), "negative coordinates, hidden");
    auto img = uiResourceRef(bmp.get("image"));
    check(img && img->type == kTypeUiImage && img->group == 0x499DB772 && img->instance == 0xCCC9AF70, "image key");
    const UiElement& text2 = root.children[1];
    check(text2.get("caption") == "two\r\nlines > here", "quoted value spans lines and holds '>'");
    check(text2.attr("transparent") && text2.attr("transparent")->empty(), "bare flag");
    check(uiColor(text2.get("outlinecolor")) == std::array<uint8_t, 3>{127, 136, 255}, "double list reads the first");
    auto str = uiStringRef(text2.get("captionres"));
    check(str && str->group == 0x7F3A262A && str->instance == 0x87 && str->index == 0, "string ref");
    check(!uiStringRef("{00000000,00000000}"), "null string ref");
    check(text2.children.size() == 1, "nested children");
    auto thumb = uiResourceRef(text2.children[0].get("thumbimage"));
    check(thumb && thumb->type == 0x856DDBAC && thumb->instance == 0xCCC30005, "three-part key");
    check(s.find(0x1008) == &text2.children[0], "find by id");
    check(s.roots[1].clsid() == "0x4d9ccdb1", "hex class id");

    const UiScript bad = UiScript::parse("<LEGACY a=1>\r\n</CHILDREN>\r\n<CHILDREN>\r\n<FOO>\r\n");
    check(bad.warnings.size() == 3, "warnings for unbalanced and unknown tags");

    check(packageGroupHash("UIText") == 0x7FA7DC7C, "UIText group hash");
    check(packageGroupHash("CAS") == 0x7F549C7F, "CAS group hash");
    check(uiInts("(1,x,3)").empty(), "malformed list");
    check(!isReia(std::vector<uint8_t>{'#', ' '}), "script is not Reia");
}

static void pixel(const RgbaImage& img, uint32_t x, uint32_t y, int r, int g, int b, int a, int tol, const char* what) {
    const uint8_t* p = &img.pixels[(size_t(y) * img.width + x) * 4];
    check(std::abs(p[0] - r) <= tol && std::abs(p[1] - g) <= tol && std::abs(p[2] - b) <= tol && std::abs(p[3] - a) <= tol,
          what);
}

static void testTga() {
    // 2x2, 32-bit, bottom-up, RLE: bottom row is one run of blue, top row raw red + green.
    std::vector<uint8_t> d(18, 0);
    d[2] = 10;
    d[12] = 2;
    d[14] = 2;
    d[16] = 32;
    for (uint8_t b : {0x81, 255, 0, 0, 200}) // run of 2: B,G,R,A
        d.push_back(b);
    for (uint8_t b : {0x01, 0, 0, 255, 255, 0, 255, 0, 128}) // 2 raw
        d.push_back(b);
    check(detectUiImage(d) == UiImageFormat::Tga, "TGA detected");
    auto img = decodeUiImage(d);
    check(img && img->width == 2 && img->height == 2, "TGA decoded");
    if (img) {
        pixel(*img, 0, 0, 255, 0, 0, 255, 0, "TGA top-left red");
        pixel(*img, 1, 0, 0, 255, 0, 128, 0, "TGA top-right green");
        pixel(*img, 0, 1, 0, 0, 255, 200, 0, "TGA bottom row blue");
    }
    d.resize(d.size() - 1);
    std::string err;
    check(!decodeUiImage(d, &err) && !err.empty(), "truncated TGA fails");
}

static void testBmp() {
    // 1x2, 24-bit, bottom-up, rows padded to 4 bytes.
    std::vector<uint8_t> d(54, 0);
    d[0] = 'B', d[1] = 'M';
    d[10] = 54;
    d[14] = 40;
    d[18] = 1;
    d[22] = 2;
    d[28] = 24;
    for (uint8_t b : {10, 20, 30, 0, 40, 50, 60, 0})
        d.push_back(b);
    auto img = decodeUiImage(d);
    check(img && img->width == 1 && img->height == 2, "BMP decoded");
    if (img) {
        pixel(*img, 0, 0, 60, 50, 40, 255, 0, "BMP top row is the last stored");
        pixel(*img, 0, 1, 30, 20, 10, 255, 0, "BMP bottom row");
    }
}

